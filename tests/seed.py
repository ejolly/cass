def seed(conn: duckdb.DuckDBPyConnection) -> None:
    """Populate an initialized DuckDB with anonymized realistic test data.

    Expects ``db.init_schema(conn)`` to have been called first.
    Data mirrors a real classroom with 15 Canvas students, 18 GH students
    (including 2 excluded and 1 unmatched), 5 Canvas + 8 GH assignments,
    75 Canvas grades/submissions, and 141 GH submissions/grades.
    """
    conn.execute("DELETE FROM meta")
    conn.execute("INSERT INTO meta (key, value) VALUES ('schema_version', '13')")
    conn.execute(
        "INSERT INTO meta (key, value) VALUES "
        "('course_name', 'TEST 101 - Intro to Testing [WI26]')"
    )

    for table, (cols, data) in _TABLES.items():
        if not data:
            continue
        placeholders = ", ".join("?" for _ in cols)
        col_str = ", ".join(cols)
        conn.executemany(
            f"INSERT INTO {table} ({col_str}) VALUES ({placeholders})",
            data,
        )

    # Snapshot synced tables (mirrors post-pull state)
    db.snapshot_canvas_synced(conn)
